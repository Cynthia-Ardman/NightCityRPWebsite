async function main() {
  const { db, ncpdLaws } = await import("@workspace/db");
  const { eq } = await import("drizzle-orm");

  let created = 0;
  let updated = 0;
  for (let i = 0; i < LAWS.length; i++) {
    const entry = LAWS[i];
    const sortOrder = i * 10;
    const [existing] = await db.select().from(ncpdLaws).where(eq(ncpdLaws.title, entry.title));
    if (existing) {
      await db
        .update(ncpdLaws)
        .set({ body: entry.body, sortOrder })
        .where(eq(ncpdLaws.id, existing.id));
      updated++;
      console.log(`  updated: ${entry.title}`);
    } else {
      await db.insert(ncpdLaws).values({ title: entry.title, body: entry.body, sortOrder });
      created++;
      console.log(`  created: ${entry.title}`);
    }
  }
  console.log(`\nDone. ${created} created, ${updated} updated (${LAWS.length} total).`);
  process.exit(0);
}

main().catch((err) => {
  console.error("Law book import failed:", err);
  process.exit(1);
});
