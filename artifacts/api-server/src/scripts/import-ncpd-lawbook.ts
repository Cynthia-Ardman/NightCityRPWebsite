// One-off operational script: import the Night City Law Book into the Book of
// Laws (ncpd_laws). Idempotent — upserts by exact title, so re-running updates
// the body/sortOrder of an existing entry instead of creating duplicates.
//
// Usage (from repo root):
//   LAWBOOK_TARGET=dev  pnpm --filter @workspace/api-server exec tsx src/scripts/import-ncpd-lawbook.ts
//   LAWBOOK_TARGET=prod pnpm --filter @workspace/api-server exec tsx src/scripts/import-ncpd-lawbook.ts
//
// Targeting prod requires LIVE_PROD_DATABASE_URL and is refused otherwise.

export {};

const target = (process.env.LAWBOOK_TARGET ?? "").toLowerCase();
if (target === "prod") {
  if (!process.env.LIVE_PROD_DATABASE_URL) {
    console.error("LAWBOOK_TARGET=prod requires LIVE_PROD_DATABASE_URL; refusing to run.");
    process.exit(1);
  }
  process.env.DATABASE_URL = process.env.LIVE_PROD_DATABASE_URL;
} else if (target !== "dev") {
  console.error("Set LAWBOOK_TARGET=dev or prod");
  process.exit(1);
}

